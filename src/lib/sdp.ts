import { ToolError } from './errors';

export interface SignalEnvelope {
  type: 'offer' | 'answer';
  sdp: string;
}

export const SIGNAL_PREFIX = 'DTX1:';
/** deflate-raw 压缩后的信封，多网卡设备压缩前会超出二维码容量 */
export const COMPRESSED_PREFIX = 'DTX2:';

export function isSignalText(text: string): boolean {
  const trimmed = text.trim();
  return trimmed.startsWith(SIGNAL_PREFIX) || trimmed.startsWith(COMPRESSED_PREFIX);
}

/** 局域网直传只需要 host 候选：丢弃 srflx/relay 等其余 candidate 行，把 SDP 压进二维码容量。 */
export function compactSdp(sdp: string): string {
  return sdp
    .split(/\r?\n/)
    .filter((line) => {
      if (line.startsWith('a=candidate:')) return / typ host(?: |$)/.test(line);
      if (line.startsWith('a=remote-candidates')) return false;
      if (line.startsWith('a=candidate-acl')) return false;
      return true;
    })
    .join('\r\n');
}

function bytesToBase64(bytes: Uint8Array): string {
  let binary = '';
  const step = 0x8000;
  for (let i = 0; i < bytes.length; i += step) {
    binary += String.fromCharCode(...bytes.subarray(i, i + step));
  }
  return btoa(binary);
}

function base64ToBytes(base64: string): Uint8Array {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

async function transformBytes(bytes: Uint8Array, compress: boolean): Promise<Uint8Array> {
  const transform = compress
    ? new CompressionStream('deflate-raw')
    : new DecompressionStream('deflate-raw');
  const writer = transform.writable.getWriter();
  // 错误统一从 readable 侧冒泡，避免 write/close 的 Promise 变成未处理拒绝
  writer.write(bytes).catch(() => {});
  writer.close().catch(() => {});
  return new Uint8Array(await new Response(transform.readable).arrayBuffer());
}

export async function encodeSignal(envelope: SignalEnvelope): Promise<string> {
  if (!envelope.sdp || !envelope.type)
    throw new ToolError(
      { zh: '连接信息生成失败', en: 'Failed to generate connection info' },
      { zh: '缺少有效的 SDP，请重新发起配对', en: 'Missing a valid SDP; start pairing again' },
    );
  const raw = new TextEncoder().encode(JSON.stringify(envelope));
  if (typeof CompressionStream === 'function' && typeof DecompressionStream === 'function') {
    try {
      return COMPRESSED_PREFIX + bytesToBase64(await transformBytes(raw, true));
    } catch {
      // 压缩失败则退回明文信封
    }
  }
  return SIGNAL_PREFIX + bytesToBase64(raw);
}

export async function decodeSignal(text: string): Promise<SignalEnvelope> {
  const trimmed = text.trim();
  const compressed = trimmed.startsWith(COMPRESSED_PREFIX);
  if (!compressed && !trimmed.startsWith(SIGNAL_PREFIX)) {
    throw new ToolError(
      { zh: '连接信息无效', en: 'Invalid connection info' },
      {
        zh: `粘贴的内容不是本工具生成的连接信息（应以 ${SIGNAL_PREFIX.slice(0, 4)} 开头）`,
        en: `The pasted content is not connection info generated by this tool (it should start with ${SIGNAL_PREFIX.slice(0, 4)})`,
      },
    );
  }
  let envelope: unknown;
  try {
    let bytes = base64ToBytes(trimmed.slice(compressed ? COMPRESSED_PREFIX.length : SIGNAL_PREFIX.length));
    if (compressed) bytes = await transformBytes(bytes, false);
    envelope = JSON.parse(new TextDecoder().decode(bytes));
  } catch {
    throw new ToolError(
      { zh: '连接信息已损坏', en: 'The connection info is corrupted' },
      { zh: '请让对方重新生成并完整复制连接信息', en: 'Ask the other side to regenerate it and copy the full connection info' },
    );
  }
  const candidate = envelope as Partial<SignalEnvelope>;
  if (
    (candidate.type !== 'offer' && candidate.type !== 'answer') ||
    typeof candidate.sdp !== 'string' ||
    !candidate.sdp.startsWith('v=0')
  ) {
    throw new ToolError(
      { zh: '连接信息格式不正确', en: 'The connection info has an invalid format' },
      { zh: '请确认复制的是完整的连接信息文本', en: 'Make sure you copied the complete connection info text' },
    );
  }
  return { type: candidate.type, sdp: candidate.sdp };
}
