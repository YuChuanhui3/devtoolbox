import { ToolError } from './errors';
import { base64ToText, normalizeBase64, textToBase64 } from './base64';

function requireUrl(url: string): string {
  const trimmed = url.trim();
  if (!trimmed)
    throw new ToolError(
      { zh: '请输入普通下载地址', en: 'Enter a direct download URL' },
      { zh: '应包含 http:// 或 https:// 等协议前缀。', en: 'It should include a protocol prefix such as http:// or https://.' },
    );
  if (!/^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//.test(trimmed)) {
    throw new ToolError(
      { zh: '下载地址缺少协议前缀', en: 'The download URL is missing the protocol prefix' },
      { zh: '请以 http:// 或 https:// 开头。', en: 'Start it with http:// or https://.' },
    );
  }
  return trimmed;
}

function stripPrefix(link: string, prefix: string): string {
  const trimmed = link.trim();
  const withoutScheme = trimmed.startsWith(prefix) ? trimmed.slice(prefix.length) : trimmed;
  if (!withoutScheme) {
    throw new ToolError(
      { zh: `专用链接缺少有效内容：${link}`, en: `The dedicated link has no valid content: ${link}` },
      { zh: `应以 ${prefix} 开头，后接 Base64 编码。`, en: `It should start with ${prefix} followed by Base64.` },
    );
  }
  return withoutScheme;
}

function decodeBase64Payload(link: string, prefix: string): string {
  const body = stripPrefix(link, prefix);
  try {
    return base64ToText(normalizeBase64(body));
  } catch {
    throw new ToolError(
      { zh: '专用链接的 Base64 内容无法解码', en: 'The Base64 content of the dedicated link cannot be decoded' },
      { zh: `请确认链接完整且为 ${prefix}Base64 形式。`, en: `Make sure the link is complete and in ${prefix}Base64 form.` },
    );
  }
}

export function encodeThunder(url: string): string {
  return `thunder://${textToBase64(`AA${requireUrl(url)}ZZ`)}`;
}

export function decodeThunder(link: string): string {
  const decoded = decodeBase64Payload(link, 'thunder://');
  if (!decoded.startsWith('AA') || !decoded.endsWith('ZZ') || decoded.length < 5) {
    throw new ToolError(
      { zh: '迅雷链接缺少 AA…ZZ 包裹', en: 'The Thunder link is missing the AA…ZZ wrapper' },
      { zh: '请确认输入的是 thunder:// 专用链接。', en: 'Make sure the input is a thunder:// dedicated link.' },
    );
  }
  return decoded.slice(2, -2);
}

export function encodeFlashget(url: string, suffix = 'sosobt'): string {
  return `flashget://${textToBase64(`[FLASHGET]${requireUrl(url)}[FLASHGET]`)}&${suffix}`;
}

export function decodeFlashget(link: string): string {
  const body = stripPrefix(link, 'flashget://');
  // 末尾 &xxx 为快车附加标记，先移除再解码。
  const base64Part = body.slice(0, body.lastIndexOf('&') === -1 ? body.length : body.lastIndexOf('&'));
  const decoded = (() => {
    try {
      return base64ToText(normalizeBase64(base64Part));
    } catch {
      throw new ToolError(
        { zh: '快车链接的 Base64 内容无法解码', en: 'The Base64 content of the FlashGet link cannot be decoded' },
        { zh: '请确认输入的是 flashget:// 专用链接。', en: 'Make sure the input is a flashget:// dedicated link.' },
      );
    }
  })();
  const match = /^\[FLASHGET\]([\s\S]*)\[FLASHGET\]$/.exec(decoded);
  if (!match) {
    throw new ToolError(
      { zh: '快车链接缺少 [FLASHGET] 标记', en: 'The FlashGet link is missing the [FLASHGET] marker' },
      { zh: '请确认链接由快车导出或使用本工具生成。', en: 'Make sure the link was exported from FlashGet or generated by this tool.' },
    );
  }
  return match[1];
}

export function encodeQqXuanfeng(url: string): string {
  return `qqdl://${textToBase64(requireUrl(url))}`;
}

export function decodeQqXuanfeng(link: string): string {
  return decodeBase64Payload(link, 'qqdl://');
}
